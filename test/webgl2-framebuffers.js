tape('WebGL1 keeps DEPTH_STENCIL_ATTACHMENT separate', function (t) {
  const gl = createContext(8, 8)
  const framebuffer = gl.createFramebuffer()
  gl.bindFramebuffer(gl.FRAMEBUFFER, framebuffer)
  const depth = gl.createRenderbuffer()
  gl.bindRenderbuffer(gl.RENDERBUFFER, depth)
  gl.renderbufferStorage(gl.RENDERBUFFER, gl.DEPTH_COMPONENT16, 8, 8)
  gl.framebufferRenderbuffer(gl.FRAMEBUFFER, gl.DEPTH_ATTACHMENT, gl.RENDERBUFFER, depth)
  const depthStencil = gl.createRenderbuffer()
  gl.bindRenderbuffer(gl.RENDERBUFFER, depthStencil)
  gl.renderbufferStorage(gl.RENDERBUFFER, gl.DEPTH_STENCIL, 8, 8)
  gl.framebufferRenderbuffer(gl.FRAMEBUFFER, gl.DEPTH_STENCIL_ATTACHMENT, gl.RENDERBUFFER, depthStencil)
  t.equal(gl.getError(), gl.NO_ERROR)
  t.equal(gl.getFramebufferAttachmentParameter(gl.FRAMEBUFFER, gl.DEPTH_ATTACHMENT, gl.FRAMEBUFFER_ATTACHMENT_OBJECT_NAME), depth)
  t.equal(gl.getFramebufferAttachmentParameter(gl.FRAMEBUFFER, gl.DEPTH_STENCIL_ATTACHMENT, gl.FRAMEBUFFER_ATTACHMENT_OBJECT_NAME), depthStencil)

  gl.bindRenderbuffer(gl.RENDERBUFFER, null)
  gl.bindFramebuffer(gl.FRAMEBUFFER, null)
  gl.deleteRenderbuffer(depthStencil)
  gl.bindFramebuffer(gl.FRAMEBUFFER, framebuffer)
  const other = gl.createRenderbuffer()
  t.equal(gl.getFramebufferAttachmentParameter(gl.FRAMEBUFFER, gl.DEPTH_STENCIL_ATTACHMENT, gl.FRAMEBUFFER_ATTACHMENT_OBJECT_NAME), depthStencil, 'orphaned object, not a reused id')
  t.notEqual(other, depthStencil)
  t.equal(gl.getError(), gl.NO_ERROR)
  destroy(gl)
  t.end()
})


'use strict'

const tape = require('tape')
const createContext = require('../index')

function createGL (t) {
  const gl = createContext(8, 8, { createWebGL2Context: true })
  t.ok(gl, 'created a WebGL2 context')
  return gl
}

function destroy (gl) {
  gl.getExtension('STACKGL_destroy_context').destroy()
}

function readPixel (gl, x, y) {
  const pixel = new Uint8Array(4)
  gl.readPixels(x, y, 1, 1, gl.RGBA, gl.UNSIGNED_BYTE, pixel)
  return Array.from(pixel)
}

function createTexture (gl, width, height, internalFormat, format, type) {
  const texture = gl.createTexture()
  gl.bindTexture(gl.TEXTURE_2D, texture)
  gl.texImage2D(gl.TEXTURE_2D, 0, internalFormat || gl.RGBA, width, height, 0, format || gl.RGBA, type || gl.UNSIGNED_BYTE, null)
  gl.texParameteri(gl.TEXTURE_2D, gl.TEXTURE_MIN_FILTER, gl.NEAREST)
  gl.texParameteri(gl.TEXTURE_2D, gl.TEXTURE_MAG_FILTER, gl.NEAREST)
  gl.bindTexture(gl.TEXTURE_2D, null)
  return texture
}

tape('clearBuffer*', function (t) {
  const gl = createGL(t)

  gl.clearBufferfv(gl.COLOR, 0, [1, 0, 0, 1])
  t.equal(gl.getError(), gl.NO_ERROR)
  t.deepEqual(readPixel(gl, 4, 4), [255, 0, 0, 255], 'plain array')
  gl.clearBufferfv(gl.COLOR, 0, new Float32Array([0, 1, 0, 1]))
  t.deepEqual(readPixel(gl, 4, 4), [0, 255, 0, 255], 'typed array')
  gl.clearBufferfv(gl.COLOR, 0, new Float32Array(new Float32Array([9, 9, 0, 0, 1, 1]).buffer, 8, 4))
  t.deepEqual(readPixel(gl, 4, 4), [0, 0, 255, 255], 'view with a byte offset')
  gl.clearBufferfv(gl.COLOR, 0, [9, 9, 1, 1, 0, 1], 2)
  t.deepEqual(readPixel(gl, 4, 4), [255, 255, 0, 255], 'srcOffset')
  gl.clearBufferfv(gl.COLOR, 0, new Float64Array([1, 0, 1, 1]))
  t.deepEqual(readPixel(gl, 4, 4), [255, 0, 255, 255], 'other typed arrays are converted')

  gl.clearBufferfv(gl.COLOR, 0, [1, 0, 0])
  t.equal(gl.getError(), gl.INVALID_VALUE, 'too few color values')
  gl.clearBufferfv(gl.COLOR, 0, [1, 0, 0, 1, 1], 2)
  t.equal(gl.getError(), gl.INVALID_VALUE, 'too few values after srcOffset')
  gl.clearBufferfv(gl.DEPTH, 0, [])
  t.equal(gl.getError(), gl.INVALID_VALUE, 'too few depth values')
  gl.clearBufferfv(gl.DEPTH, 0, [1])
  gl.clearBufferiv(gl.STENCIL, 0, [0])
  gl.clearBufferfi(gl.DEPTH_STENCIL, 0, 1, 0)
  t.equal(gl.getError(), gl.NO_ERROR, 'depth and stencil clears')

  gl.clearBufferfv(gl.STENCIL, 0, [0])
  t.equal(gl.getError(), gl.INVALID_ENUM, 'fv rejects STENCIL')
  gl.clearBufferiv(gl.DEPTH, 0, [0])
  t.equal(gl.getError(), gl.INVALID_ENUM, 'iv rejects DEPTH')
  gl.clearBufferuiv(gl.DEPTH, 0, [0])
  t.equal(gl.getError(), gl.INVALID_ENUM, 'uiv rejects DEPTH')
  gl.clearBufferfi(gl.COLOR, 0, 1, 0)
  t.equal(gl.getError(), gl.INVALID_ENUM, 'fi only clears DEPTH_STENCIL')
  gl.clearBufferfv(gl.COLOR, gl.getParameter(gl.MAX_DRAW_BUFFERS), [0, 0, 0, 0])
  t.equal(gl.getError(), gl.INVALID_VALUE, 'draw buffer out of range')
  gl.clearBufferfv(gl.DEPTH, 1, [1])
  t.equal(gl.getError(), gl.INVALID_VALUE, 'depth has a single draw buffer')
  gl.clearBufferfi(gl.DEPTH_STENCIL, 1, 1, 0)
  t.equal(gl.getError(), gl.INVALID_VALUE, 'depth stencil has a single draw buffer')
  t.throws(function () {
    gl.clearBufferfv(gl.COLOR, 0, 1)
  }, TypeError)

  const framebuffer = gl.createFramebuffer()
  gl.bindFramebuffer(gl.FRAMEBUFFER, framebuffer)
  const unsigned = createTexture(gl, 1, 1, gl.RGBA8UI, gl.RGBA_INTEGER, gl.UNSIGNED_BYTE)
  gl.framebufferTexture2D(gl.FRAMEBUFFER, gl.COLOR_ATTACHMENT0, gl.TEXTURE_2D, unsigned, 0)
  t.equal(gl.checkFramebufferStatus(gl.FRAMEBUFFER), gl.FRAMEBUFFER_COMPLETE)
  gl.clearBufferuiv(gl.COLOR, 0, [1, 2, 3, 4])
  t.equal(gl.getError(), gl.NO_ERROR)
  const unsignedPixel = new Uint32Array(4)
  gl.readPixels(0, 0, 1, 1, gl.RGBA_INTEGER, gl.UNSIGNED_INT, unsignedPixel)
  t.deepEqual(Array.from(unsignedPixel), [1, 2, 3, 4], 'unsigned integer clear')

  const signed = createTexture(gl, 1, 1, gl.RGBA8I, gl.RGBA_INTEGER, gl.BYTE)
  gl.framebufferTexture2D(gl.FRAMEBUFFER, gl.COLOR_ATTACHMENT0, gl.TEXTURE_2D, signed, 0)
  gl.clearBufferiv(gl.COLOR, 0, new Int32Array([-1, -2, 3, 4]))
  t.equal(gl.getError(), gl.NO_ERROR)
  const signedPixel = new Int32Array(4)
  gl.readPixels(0, 0, 1, 1, gl.RGBA_INTEGER, gl.INT, signedPixel)
  t.deepEqual(Array.from(signedPixel), [-1, -2, 3, 4], 'signed integer clear')

  destroy(gl)
  t.end()
})

tape('readBuffer and drawBuffers', function (t) {
  const gl = createGL(t)

  t.equal(gl.getParameter(gl.READ_BUFFER), gl.BACK)
  t.equal(gl.getParameter(gl.DRAW_BUFFER0), gl.BACK)
  t.equal(gl.getParameter(gl.DRAW_BUFFER1), gl.NONE)
  gl.clearColor(1, 0, 0, 1)
  gl.clear(gl.COLOR_BUFFER_BIT)
  gl.drawBuffers([gl.NONE])
  t.equal(gl.getError(), gl.NO_ERROR)
  t.equal(gl.getParameter(gl.DRAW_BUFFER0), gl.NONE)
  gl.clearColor(0, 1, 0, 1)
  gl.clear(gl.COLOR_BUFFER_BIT)
  t.deepEqual(readPixel(gl, 4, 4), [255, 0, 0, 255], 'NONE disables drawing to the default framebuffer')
  gl.drawBuffers([gl.BACK])
  gl.clear(gl.COLOR_BUFFER_BIT)
  t.deepEqual(readPixel(gl, 4, 4), [0, 255, 0, 255], 'BACK restores it')
  gl.readBuffer(gl.NONE)
  t.equal(gl.getParameter(gl.READ_BUFFER), gl.NONE)
  gl.readBuffer(gl.BACK)
  t.equal(gl.getError(), gl.NO_ERROR)
  gl.drawBuffers([gl.COLOR_ATTACHMENT0])
  t.equal(gl.getError(), gl.INVALID_OPERATION, 'attachments are not valid for the default framebuffer')
  gl.drawBuffers([gl.BACK, gl.NONE])
  t.equal(gl.getError(), gl.INVALID_OPERATION, 'the default framebuffer has one draw buffer')
  gl.readBuffer(gl.COLOR_ATTACHMENT0)
  t.equal(gl.getError(), gl.INVALID_OPERATION, 'attachments are not valid read buffers for the default framebuffer')
  gl.drawBuffers([0x1234])
  t.equal(gl.getError(), gl.INVALID_ENUM)
  gl.readBuffer(0x1234)
  t.equal(gl.getError(), gl.INVALID_ENUM)
  t.throws(function () {
    gl.drawBuffers(gl.BACK)
  }, TypeError)

  const framebuffer = gl.createFramebuffer()
  gl.bindFramebuffer(gl.FRAMEBUFFER, framebuffer)
  const first = createTexture(gl, 2, 2)
  const second = createTexture(gl, 2, 2)
  gl.framebufferTexture2D(gl.FRAMEBUFFER, gl.COLOR_ATTACHMENT0, gl.TEXTURE_2D, first, 0)
  gl.framebufferTexture2D(gl.FRAMEBUFFER, gl.COLOR_ATTACHMENT1, gl.TEXTURE_2D, second, 0)
  t.equal(gl.checkFramebufferStatus(gl.FRAMEBUFFER), gl.FRAMEBUFFER_COMPLETE)
  t.equal(gl.getParameter(gl.READ_BUFFER), gl.COLOR_ATTACHMENT0, 'framebuffers start reading from attachment 0')
  t.equal(gl.getParameter(gl.DRAW_BUFFER0), gl.COLOR_ATTACHMENT0)
  t.equal(gl.getParameter(gl.DRAW_BUFFER1), gl.NONE)

  gl.drawBuffers([gl.COLOR_ATTACHMENT0, gl.COLOR_ATTACHMENT1])
  t.equal(gl.getError(), gl.NO_ERROR)
  t.equal(gl.getParameter(gl.DRAW_BUFFER1), gl.COLOR_ATTACHMENT1)
  gl.clearColor(0, 0, 1, 1)
  gl.clear(gl.COLOR_BUFFER_BIT)
  gl.readBuffer(gl.COLOR_ATTACHMENT1)
  t.equal(gl.getParameter(gl.READ_BUFFER), gl.COLOR_ATTACHMENT1)
  t.deepEqual(readPixel(gl, 0, 0), [0, 0, 255, 255], 'clear writes both attachments')

  gl.drawBuffers([gl.NONE, gl.COLOR_ATTACHMENT1])
  gl.clearBufferfv(gl.COLOR, 1, [1, 1, 0, 1])
  t.deepEqual(readPixel(gl, 0, 0), [255, 255, 0, 255], 'clearBufferfv targets the draw buffer index')
  gl.readBuffer(gl.COLOR_ATTACHMENT0)
  t.deepEqual(readPixel(gl, 0, 0), [0, 0, 255, 255], 'attachment 0 was not touched')

  gl.drawBuffers([gl.COLOR_ATTACHMENT1, gl.COLOR_ATTACHMENT0])
  t.equal(gl.getError(), gl.INVALID_OPERATION, 'attachments must match their index')
  gl.drawBuffers([gl.BACK])
  t.equal(gl.getError(), gl.INVALID_OPERATION, 'BACK is not valid for a framebuffer')
  gl.readBuffer(gl.BACK)
  t.equal(gl.getError(), gl.INVALID_OPERATION, 'BACK is not a valid read buffer for a framebuffer')
  const tooMany = []
  for (let i = 0; i <= gl.getParameter(gl.MAX_DRAW_BUFFERS); ++i) {
    tooMany.push(gl.NONE)
  }
  gl.drawBuffers(tooMany)
  t.equal(gl.getError(), gl.INVALID_VALUE, 'too many draw buffers')

  gl.bindFramebuffer(gl.FRAMEBUFFER, null)
  t.equal(gl.getParameter(gl.READ_BUFFER), gl.BACK, 'read buffer is framebuffer state')
  t.equal(gl.getParameter(gl.DRAW_BUFFER0), gl.BACK, 'draw buffers are framebuffer state')
  gl.bindFramebuffer(gl.FRAMEBUFFER, framebuffer)
  t.equal(gl.getParameter(gl.READ_BUFFER), gl.COLOR_ATTACHMENT0)
  t.equal(gl.getParameter(gl.DRAW_BUFFER1), gl.COLOR_ATTACHMENT1)

  destroy(gl)
  t.end()
})

tape('blitFramebuffer and multisampled renderbuffers', function (t) {
  const gl = createGL(t)
  const maxSamples = gl.getParameter(gl.MAX_SAMPLES)
  t.ok(maxSamples >= 4, 'MAX_SAMPLES is at least 4')
  const samples = Math.min(4, maxSamples)

  const renderbuffer = gl.createRenderbuffer()
  gl.renderbufferStorageMultisample(gl.RENDERBUFFER, samples, gl.RGBA8, 4, 4)
  t.equal(gl.getError(), gl.INVALID_OPERATION, 'no renderbuffer bound')
  gl.bindRenderbuffer(gl.RENDERBUFFER, renderbuffer)
  gl.renderbufferStorageMultisample(gl.RENDERBUFFER, samples, gl.RGBA8, -4, 4)
  t.equal(gl.getError(), gl.INVALID_VALUE, 'negative size')
  gl.renderbufferStorageMultisample(gl.RENDERBUFFER, maxSamples + 1, gl.RGBA8, 4, 4)
  t.notEqual(gl.getError(), gl.NO_ERROR, 'too many samples')
  gl.renderbufferStorageMultisample(gl.RENDERBUFFER, samples, gl.RGBA8, 4, 4)
  t.equal(gl.getError(), gl.NO_ERROR)
  t.equal(gl.getRenderbufferParameter(gl.RENDERBUFFER, gl.RENDERBUFFER_SAMPLES), samples)
  t.equal(gl.getRenderbufferParameter(gl.RENDERBUFFER, gl.RENDERBUFFER_WIDTH), 4)
  t.equal(gl.getRenderbufferParameter(gl.RENDERBUFFER, gl.RENDERBUFFER_INTERNAL_FORMAT), gl.RGBA8)
  gl.renderbufferStorage(gl.RENDERBUFFER, gl.RGBA8, 4, 4)
  t.equal(gl.getRenderbufferParameter(gl.RENDERBUFFER, gl.RENDERBUFFER_SAMPLES), 0, 'renderbufferStorage resets the sample count')
  gl.renderbufferStorageMultisample(gl.RENDERBUFFER, samples, gl.RGBA8, 4, 4)

  const multisampled = gl.createFramebuffer()
  gl.bindFramebuffer(gl.FRAMEBUFFER, multisampled)
  gl.framebufferRenderbuffer(gl.FRAMEBUFFER, gl.COLOR_ATTACHMENT0, gl.RENDERBUFFER, renderbuffer)
  t.equal(gl.checkFramebufferStatus(gl.FRAMEBUFFER), gl.FRAMEBUFFER_COMPLETE)
  gl.clearColor(0, 0, 1, 1)
  gl.clear(gl.COLOR_BUFFER_BIT)

  const resolved = gl.createFramebuffer()
  const texture = createTexture(gl, 4, 4)
  gl.bindFramebuffer(gl.DRAW_FRAMEBUFFER, resolved)
  gl.framebufferTexture2D(gl.DRAW_FRAMEBUFFER, gl.COLOR_ATTACHMENT0, gl.TEXTURE_2D, texture, 0)
  t.equal(gl.getParameter(gl.READ_FRAMEBUFFER_BINDING), multisampled)
  t.equal(gl.getParameter(gl.DRAW_FRAMEBUFFER_BINDING), resolved)
  t.equal(gl.getParameter(gl.FRAMEBUFFER_BINDING), resolved, 'FRAMEBUFFER_BINDING is the draw binding')
  t.equal(gl.checkFramebufferStatus(gl.DRAW_FRAMEBUFFER), gl.FRAMEBUFFER_COMPLETE)
  t.equal(gl.checkFramebufferStatus(gl.READ_FRAMEBUFFER), gl.FRAMEBUFFER_COMPLETE)

  gl.blitFramebuffer(0, 0, 4, 4, 0, 0, 4, 4, gl.COLOR_BUFFER_BIT, gl.NEAREST)
  t.equal(gl.getError(), gl.NO_ERROR, 'resolve blit')
  gl.bindFramebuffer(gl.READ_FRAMEBUFFER, resolved)
  t.deepEqual(readPixel(gl, 1, 1), [0, 0, 255, 255], 'the resolved texture holds the color')

  gl.blitFramebuffer(0, 0, 4, 4, 0, 0, 4, 4, gl.COLOR_BUFFER_BIT, 0x1234)
  t.equal(gl.getError(), gl.INVALID_ENUM, 'bad filter')
  gl.blitFramebuffer(0, 0, 4, 4, 0, 0, 4, 4, gl.DEPTH_BUFFER_BIT, gl.LINEAR)
  t.equal(gl.getError(), gl.INVALID_OPERATION, 'depth cannot be filtered')
  gl.blitFramebuffer(0, 0, 4, 4, 0, 0, 4, 4, 0x8000, gl.NEAREST)
  t.equal(gl.getError(), gl.INVALID_VALUE, 'bad mask')

  gl.bindFramebuffer(gl.READ_FRAMEBUFFER, null)
  gl.bindFramebuffer(gl.DRAW_FRAMEBUFFER, null)
  gl.clearColor(1, 0, 0, 1)
  gl.clear(gl.COLOR_BUFFER_BIT)
  gl.bindFramebuffer(gl.READ_FRAMEBUFFER, resolved)
  gl.blitFramebuffer(0, 0, 4, 4, 0, 0, 8, 8, gl.COLOR_BUFFER_BIT, gl.LINEAR)
  t.equal(gl.getError(), gl.NO_ERROR, 'blit into the default framebuffer')
  gl.bindFramebuffer(gl.READ_FRAMEBUFFER, null)
  t.deepEqual(readPixel(gl, 4, 4), [0, 0, 255, 255], 'the default framebuffer received the blit')

  destroy(gl)
  t.end()
})

tape('invalidateFramebuffer', function (t) {
  const gl = createGL(t)

  gl.invalidateFramebuffer(gl.FRAMEBUFFER, [gl.COLOR, gl.DEPTH, gl.STENCIL])
  t.equal(gl.getError(), gl.NO_ERROR, 'default framebuffer attachments')
  gl.invalidateSubFramebuffer(gl.FRAMEBUFFER, [gl.COLOR], 0, 0, 2, 2)
  t.equal(gl.getError(), gl.NO_ERROR)
  gl.invalidateFramebuffer(gl.FRAMEBUFFER, [gl.COLOR_ATTACHMENT0])
  t.equal(gl.getError(), gl.INVALID_ENUM, 'attachments are not valid for the default framebuffer')
  gl.invalidateFramebuffer(gl.RENDERBUFFER, [gl.COLOR])
  t.equal(gl.getError(), gl.INVALID_ENUM, 'bad target')
  gl.invalidateSubFramebuffer(gl.FRAMEBUFFER, [gl.COLOR], 0, 0, -1, 2)
  t.equal(gl.getError(), gl.INVALID_VALUE, 'negative size')
  t.throws(function () {
    gl.invalidateFramebuffer(gl.FRAMEBUFFER, gl.COLOR)
  }, TypeError)

  const framebuffer = gl.createFramebuffer()
  gl.bindFramebuffer(gl.FRAMEBUFFER, framebuffer)
  gl.framebufferTexture2D(gl.FRAMEBUFFER, gl.COLOR_ATTACHMENT0, gl.TEXTURE_2D, createTexture(gl, 2, 2), 0)
  gl.invalidateFramebuffer(gl.FRAMEBUFFER, [gl.COLOR_ATTACHMENT0, gl.DEPTH_ATTACHMENT, gl.DEPTH_STENCIL_ATTACHMENT])
  t.equal(gl.getError(), gl.NO_ERROR)
  gl.invalidateSubFramebuffer(gl.DRAW_FRAMEBUFFER, [gl.COLOR_ATTACHMENT0], 0, 0, 1, 1)
  t.equal(gl.getError(), gl.NO_ERROR)
  gl.invalidateFramebuffer(gl.FRAMEBUFFER, [gl.COLOR])
  t.equal(gl.getError(), gl.INVALID_ENUM, 'default attachments are not valid for a framebuffer')
  gl.invalidateFramebuffer(gl.FRAMEBUFFER, [gl.COLOR_ATTACHMENT0 + gl.getParameter(gl.MAX_COLOR_ATTACHMENTS)])
  t.equal(gl.getError(), gl.INVALID_OPERATION, 'attachment beyond the maximum')

  destroy(gl)
  t.end()
})

tape('getFramebufferAttachmentParameter', function (t) {
  const gl = createGL(t)

  t.equal(gl.getFramebufferAttachmentParameter(gl.FRAMEBUFFER, gl.BACK, gl.FRAMEBUFFER_ATTACHMENT_OBJECT_TYPE), gl.FRAMEBUFFER_DEFAULT)
  t.equal(gl.getFramebufferAttachmentParameter(gl.FRAMEBUFFER, gl.BACK, gl.FRAMEBUFFER_ATTACHMENT_RED_SIZE), 8)
  t.equal(gl.getFramebufferAttachmentParameter(gl.FRAMEBUFFER, gl.BACK, gl.FRAMEBUFFER_ATTACHMENT_ALPHA_SIZE), 8)
  t.equal(gl.getFramebufferAttachmentParameter(gl.FRAMEBUFFER, gl.BACK, gl.FRAMEBUFFER_ATTACHMENT_COMPONENT_TYPE), gl.UNSIGNED_NORMALIZED)
  t.equal(gl.getFramebufferAttachmentParameter(gl.FRAMEBUFFER, gl.BACK, gl.FRAMEBUFFER_ATTACHMENT_COLOR_ENCODING), gl.LINEAR)
  t.ok(gl.getFramebufferAttachmentParameter(gl.FRAMEBUFFER, gl.DEPTH, gl.FRAMEBUFFER_ATTACHMENT_DEPTH_SIZE) > 0, 'default depth')
  t.equal(gl.getError(), gl.NO_ERROR)
  t.equal(gl.getFramebufferAttachmentParameter(gl.FRAMEBUFFER, gl.STENCIL, gl.FRAMEBUFFER_ATTACHMENT_OBJECT_TYPE), gl.NONE, 'no stencil was requested')
  t.equal(gl.getError(), gl.NO_ERROR)
  t.equal(gl.getFramebufferAttachmentParameter(gl.FRAMEBUFFER, gl.STENCIL, gl.FRAMEBUFFER_ATTACHMENT_STENCIL_SIZE), null)
  t.equal(gl.getError(), gl.INVALID_OPERATION, 'missing attachments only answer OBJECT_TYPE')
  const withStencil = createContext(8, 8, { createWebGL2Context: true, stencil: true })
  t.equal(withStencil.getFramebufferAttachmentParameter(gl.FRAMEBUFFER, gl.STENCIL, gl.FRAMEBUFFER_ATTACHMENT_OBJECT_TYPE), gl.FRAMEBUFFER_DEFAULT)
  t.ok(withStencil.getFramebufferAttachmentParameter(gl.FRAMEBUFFER, gl.STENCIL, gl.FRAMEBUFFER_ATTACHMENT_STENCIL_SIZE) > 0, 'default stencil')
  t.equal(withStencil.getError(), gl.NO_ERROR)
  destroy(withStencil)
  t.equal(gl.getFramebufferAttachmentParameter(gl.FRAMEBUFFER, gl.BACK, gl.FRAMEBUFFER_ATTACHMENT_OBJECT_NAME), null)
  t.equal(gl.getError(), gl.INVALID_ENUM, 'the default framebuffer has no object names')
  t.equal(gl.getFramebufferAttachmentParameter(gl.FRAMEBUFFER, gl.COLOR_ATTACHMENT0, gl.FRAMEBUFFER_ATTACHMENT_OBJECT_TYPE), null)
  t.equal(gl.getError(), gl.INVALID_ENUM, 'attachments are not valid for the default framebuffer')
  t.equal(gl.getFramebufferAttachmentParameter(gl.RENDERBUFFER, gl.BACK, gl.FRAMEBUFFER_ATTACHMENT_OBJECT_TYPE), null)
  t.equal(gl.getError(), gl.INVALID_ENUM, 'bad target')

  const framebuffer = gl.createFramebuffer()
  gl.bindFramebuffer(gl.FRAMEBUFFER, framebuffer)
  const texture = createTexture(gl, 2, 2)
  gl.framebufferTexture2D(gl.FRAMEBUFFER, gl.COLOR_ATTACHMENT0, gl.TEXTURE_2D, texture, 0)
  t.equal(gl.getFramebufferAttachmentParameter(gl.FRAMEBUFFER, gl.COLOR_ATTACHMENT0, gl.FRAMEBUFFER_ATTACHMENT_OBJECT_TYPE), gl.TEXTURE)
  t.equal(gl.getFramebufferAttachmentParameter(gl.FRAMEBUFFER, gl.COLOR_ATTACHMENT0, gl.FRAMEBUFFER_ATTACHMENT_OBJECT_NAME), texture)
  t.equal(gl.getFramebufferAttachmentParameter(gl.FRAMEBUFFER, gl.COLOR_ATTACHMENT0, gl.FRAMEBUFFER_ATTACHMENT_COMPONENT_TYPE), gl.UNSIGNED_NORMALIZED)
  t.equal(gl.getFramebufferAttachmentParameter(gl.FRAMEBUFFER, gl.COLOR_ATTACHMENT0, gl.FRAMEBUFFER_ATTACHMENT_COLOR_ENCODING), gl.LINEAR)
  t.equal(gl.getFramebufferAttachmentParameter(gl.FRAMEBUFFER, gl.COLOR_ATTACHMENT0, gl.FRAMEBUFFER_ATTACHMENT_TEXTURE_LAYER), 0)
  t.equal(gl.getFramebufferAttachmentParameter(gl.FRAMEBUFFER, gl.COLOR_ATTACHMENT0, gl.FRAMEBUFFER_ATTACHMENT_RED_SIZE), 8)
  t.equal(gl.getFramebufferAttachmentParameter(gl.READ_FRAMEBUFFER, gl.COLOR_ATTACHMENT0, gl.FRAMEBUFFER_ATTACHMENT_OBJECT_NAME), texture, 'read target')
  t.equal(gl.getFramebufferAttachmentParameter(gl.FRAMEBUFFER, gl.DEPTH_ATTACHMENT, gl.FRAMEBUFFER_ATTACHMENT_OBJECT_TYPE), gl.NONE)
  t.equal(gl.getError(), gl.NO_ERROR)

  destroy(gl)
  t.end()
})

tape('RENDERBUFFER_SAMPLES reports the allocated sample count', function (t) {
  const gl = createContext(8, 8, { createWebGL2Context: true })
  const supported = Array.from(gl.getInternalformatParameter(gl.RENDERBUFFER, gl.RGBA8, gl.SAMPLES))
  const renderbuffer = gl.createRenderbuffer()
  gl.bindRenderbuffer(gl.RENDERBUFFER, renderbuffer)
  gl.renderbufferStorageMultisample(gl.RENDERBUFFER, 1, gl.RGBA8, 4, 4)
  const samples = gl.getRenderbufferParameter(gl.RENDERBUFFER, gl.RENDERBUFFER_SAMPLES)
  t.ok(supported.includes(samples), 'rounded up to a supported count: ' + samples)
  gl.renderbufferStorageMultisample(gl.RENDERBUFFER, 0, gl.RGBA8, 4, 4)
  t.equal(gl.getRenderbufferParameter(gl.RENDERBUFFER, gl.RENDERBUFFER_SAMPLES), 0)
  gl.getExtension('STACKGL_destroy_context').destroy()
  t.end()
})

tape('DEPTH_STENCIL_ATTACHMENT queries after the attachments are deleted', function (t) {
  const gl = createContext(8, 8, { createWebGL2Context: true })
  const framebuffer = gl.createFramebuffer()
  gl.bindFramebuffer(gl.FRAMEBUFFER, framebuffer)
  const depth = gl.createRenderbuffer()
  gl.bindRenderbuffer(gl.RENDERBUFFER, depth)
  gl.renderbufferStorage(gl.RENDERBUFFER, gl.DEPTH_COMPONENT16, 4, 4)
  const stencil = gl.createRenderbuffer()
  gl.bindRenderbuffer(gl.RENDERBUFFER, stencil)
  gl.renderbufferStorage(gl.RENDERBUFFER, gl.STENCIL_INDEX8, 4, 4)
  gl.framebufferRenderbuffer(gl.FRAMEBUFFER, gl.DEPTH_ATTACHMENT, gl.RENDERBUFFER, depth)
  gl.framebufferRenderbuffer(gl.FRAMEBUFFER, gl.STENCIL_ATTACHMENT, gl.RENDERBUFFER, stencil)
  gl.getFramebufferAttachmentParameter(gl.FRAMEBUFFER, gl.DEPTH_STENCIL_ATTACHMENT, gl.FRAMEBUFFER_ATTACHMENT_OBJECT_TYPE)
  t.equal(gl.getError(), gl.INVALID_OPERATION, 'different depth and stencil attachments')
  gl.deleteRenderbuffer(depth)
  gl.deleteRenderbuffer(stencil)
  t.equal(gl.getFramebufferAttachmentParameter(gl.FRAMEBUFFER, gl.DEPTH_STENCIL_ATTACHMENT, gl.FRAMEBUFFER_ATTACHMENT_OBJECT_TYPE), gl.NONE)
  t.equal(gl.getError(), gl.NO_ERROR, 'both detached')
  gl.getExtension('STACKGL_destroy_context').destroy()
  t.end()
})

tape('DEPTH_STENCIL_ATTACHMENT queries compare attached objects', function (t) {
  const gl = createGL(t)
  const framebuffer = gl.createFramebuffer()
  gl.bindFramebuffer(gl.FRAMEBUFFER, framebuffer)
  const depth = gl.createRenderbuffer()
  gl.bindRenderbuffer(gl.RENDERBUFFER, depth)
  gl.renderbufferStorage(gl.RENDERBUFFER, gl.DEPTH_COMPONENT16, 8, 8)
  gl.framebufferRenderbuffer(gl.FRAMEBUFFER, gl.DEPTH_ATTACHMENT, gl.RENDERBUFFER, depth)
  gl.bindRenderbuffer(gl.RENDERBUFFER, null)
  gl.bindFramebuffer(gl.FRAMEBUFFER, null)
  gl.deleteRenderbuffer(depth)
  gl.bindFramebuffer(gl.FRAMEBUFFER, framebuffer)

  const stencil = gl.createRenderbuffer()
  gl.bindRenderbuffer(gl.RENDERBUFFER, stencil)
  gl.renderbufferStorage(gl.RENDERBUFFER, gl.STENCIL_INDEX8, 8, 8)
  gl.framebufferRenderbuffer(gl.FRAMEBUFFER, gl.STENCIL_ATTACHMENT, gl.RENDERBUFFER, stencil)
  t.equal(gl.getError(), gl.NO_ERROR)

  t.equal(gl.getFramebufferAttachmentParameter(gl.FRAMEBUFFER, gl.DEPTH_ATTACHMENT, gl.FRAMEBUFFER_ATTACHMENT_OBJECT_NAME), depth, 'orphaned depth')
  t.equal(gl.getFramebufferAttachmentParameter(gl.FRAMEBUFFER, gl.STENCIL_ATTACHMENT, gl.FRAMEBUFFER_ATTACHMENT_OBJECT_NAME), stencil, 'stencil')
  t.equal(gl.getFramebufferAttachmentParameter(gl.FRAMEBUFFER, gl.DEPTH_STENCIL_ATTACHMENT, gl.FRAMEBUFFER_ATTACHMENT_OBJECT_NAME), null)
  t.equal(gl.getError(), gl.INVALID_OPERATION, 'different objects')

  destroy(gl)
  t.end()
})

